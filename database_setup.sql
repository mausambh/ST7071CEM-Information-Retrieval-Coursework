/*
   ------------------------------------------------------------
   TASK 1 COUNTS
   ------------------------------------------------------------
*/

SELECT COUNT(*) AS RESEARCHERS
FROM RESEARCHERS;


SELECT COUNT(*) AS PUBLICATIONS
FROM PUBLICATIONS;


SELECT COUNT(*) AS PUBLICATION_RESEARCHER_LINKS
FROM PUBLICATION_RESEARCHERS;


SELECT COUNT(*) AS VOCABULARY_TERMS
FROM TERM_INDEX;


SELECT COUNT(*) AS DOCUMENT_VECTORS
FROM DOC_VECTORS;


SELECT COUNT(*) AS INVERTED_INDEX_POSTINGS
FROM INVERTED_INDEX;


/*
   Combined Task 1 index verification.
*/

SELECT

    (SELECT COUNT(*)
     FROM PUBLICATIONS)
        AS PUBLICATIONS,

    (SELECT COUNT(*)
     FROM DOC_VECTORS)
        AS DOCUMENT_VECTORS,

    (SELECT COUNT(*)
     FROM TERM_INDEX)
        AS TERMS,

    (SELECT COUNT(*)
     FROM INVERTED_INDEX)
        AS POSTINGS

FROM DUAL;


/*
   ------------------------------------------------------------
   TASK 1 PUBLICATION METADATA
   ------------------------------------------------------------
*/

SELECT

    COUNT(*) AS TOTAL_PUBLICATIONS,

    SUM(
        CASE
            WHEN PUBLICATION_DATE IS NOT NULL
            THEN 1
            ELSE 0
        END
    ) AS WITH_PUBLICATION_DATE,

    SUM(
        CASE
            WHEN AUTHOR_PROFILES_JSON IS NOT NULL
             AND DBMS_LOB.GETLENGTH(
                    AUTHOR_PROFILES_JSON
                 ) > 2
            THEN 1
            ELSE 0
        END
    ) AS WITH_AUTHOR_PROFILES

FROM PUBLICATIONS;


/*
   Research-output category distribution.
*/

SELECT

    PUBLICATION_TYPE,

    COUNT(*) AS TOTAL

FROM PUBLICATIONS

GROUP BY
    PUBLICATION_TYPE

ORDER BY
    TOTAL DESC,
    PUBLICATION_TYPE;


/*
   ------------------------------------------------------------
   TASK 2 COUNTS
   ------------------------------------------------------------
*/

SELECT COUNT(*) AS CLUSTERING_DOCUMENTS
FROM CLUSTER_DOCUMENTS;


SELECT

    COURSEWORK_CATEGORY,

    COUNT(*) AS DOCUMENTS

FROM CLUSTER_DOCUMENTS

GROUP BY
    COURSEWORK_CATEGORY

ORDER BY
    COURSEWORK_CATEGORY;


/*
   Discovered K-Means cluster composition.
*/

SELECT

    CLUSTER_ID,

    COURSEWORK_CATEGORY,

    COUNT(*) AS DOCUMENTS

FROM CLUSTER_DOCUMENTS

GROUP BY
    CLUSTER_ID,
    COURSEWORK_CATEGORY

ORDER BY
    CLUSTER_ID,
    COURSEWORK_CATEGORY;


/*
   ------------------------------------------------------------
   PREDICTION HISTORY
   ------------------------------------------------------------
*/

SELECT COUNT(*) AS SAVED_PREDICTIONS
FROM CLUSTER_PREDICTIONS;


/*
   Display recent prediction history.

   The Oracle table retains the precise stored timestamp. Django
   converts it to the configured Asia/Kathmandu timezone and formats
   it cleanly for the web interface.
*/

SELECT

    PREDICTION_ID,

    DBMS_LOB.SUBSTR(
        DOCUMENT_TEXT,
        120,
        1
    ) AS DOCUMENT_PREVIEW,

    PREDICTED_CLUSTER,

    PREDICTED_CATEGORY,

    DISTANCE_TO_CENTROID,

    PREDICTED_AT

FROM CLUSTER_PREDICTIONS

ORDER BY
    PREDICTED_AT DESC

FETCH FIRST 10 ROWS ONLY;